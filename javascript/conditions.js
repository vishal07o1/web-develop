// check if another number is greater than another number

let num1 = 5;
let num2 = 10;

if (num1 > num2) {
  console.log("num1 is greater than num2");
} else {
  console.log("num2 is greater than num1");
}
// check if a string is equal to another string

let str1 = "Hello";
let str2 = "World";

if (str1 === str2) {
  console.log("str1 is equal to str2");
} else {
  console.log("str1 is not equal to str2");
}
// check if data type is a number

let data = 42;

if (typeof data === "number") {
  //=== for data type checking
  console.log("data is a number");
} else {
  console.log("data is not a number");
}

// check if boolean value is true or false

let isTrue = true;

if (isTrue) {
  console.log("The value is true");
} else {
  console.log("The value is false");
}
// if array is empty or not

let arr = [];

if (arr.length === 0) {
  console.log("The array is empty");
} else {
  console.log("The array is not empty");
}
